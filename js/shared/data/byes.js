// NFL bye weeks by season, shared by Draft Strategist and Lineup Strategist (refactor chunk 7C;
// replaced MLS's TEAM_BYES and MDS's BYE_WEEKS_2026).
//
// Don't edit the table by hand. Each May, once the NFL publishes the schedule, run
//   node scripts/update-byes.mjs <season>
// and bump CACHE_NAME in sw.js, so browsers fetch the new table instead of the cached one.
// It downloads nflverse's schedule (github.com/nflverse/nfldata, data/games.csv), gives each
// team the regular-season week it has no game, and rewrites only that season's line below.
// Team codes are the apps' own (the Rams are LAR; nflverse writes LA).

    export const BYE_WEEKS = {
        // --- BYE_WEEKS (generated by scripts/update-byes.mjs, one line per season) ---
        2026: { ARI: 14, ATL: 11, BAL: 13, BUF: 7, CAR: 5, CHI: 10, CIN: 6, CLE: 11, DAL: 14, DEN: 10, DET: 6, GB: 11, HOU: 8, IND: 13, JAX: 7, KC: 5, LAC: 7, LAR: 11, LV: 13, MIA: 6, MIN: 6, NE: 11, NO: 8, NYG: 8, NYJ: 13, PHI: 10, PIT: 9, SEA: 11, SF: 8, TB: 10, TEN: 9, WAS: 7 },
        // --- END BYE_WEEKS ---
    };

    // The week `team` is on bye in `season`, or null. An unknown season (for example next
    // season before the script has been run for it) or team gives null, never another
    // season's week. `season` may be a number or Sleeper's string ("2026").
    export function getByeWeek(team, season) {
        if (team == null || season == null) return null;
        const weeks = Object.hasOwn(BYE_WEEKS, season) ? BYE_WEEKS[season] : null;
        if (!weeks || !Object.hasOwn(weeks, team)) return null;
        return weeks[team];
    }
